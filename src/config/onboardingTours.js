import { getPlanRank, hasPlanAccess } from '../utils/subscriptionUtils';

/**
 * Role, permission, and subscription predicates shared across tours.
 */
export const isFinProUser = (ctx) => Boolean(ctx?.isFinProVerified);

export const isOwnerOrPrimary = (ctx) => {
    const user = ctx?.user;
    if (!user) return false;
    return !user.is_sub_id && user.role !== 'sub_id' && user.role !== 'SUB_ID';
};

export const hasSubscriptionOrBasic = (ctx, featureId) => {
    if (!featureId) return true;
    return hasPlanAccess(ctx?.activePlan || 'Free Plan', featureId);
};

export const getUserPlanRank = (ctx) => getPlanRank(ctx?.activePlan || 'Free Plan');

